"""Manage alternate phrasings of golden-set questions (evals/rewordings.yaml).

A rewording inherits every expectation of its golden question, so it is used in
scored runs only after a human approves it.

  python -m tools.rewordings export              # write data/review/rewordings_review.xlsx
  python -m tools.rewordings import [FILE]       # apply Decision column back to the YAML
  python -m tools.rewordings propose --per-question 2 [--ids COV-001,NC-003]
                                                 # ask Claude for new drafts (status: pending)
  python -m tools.rewordings status              # counts by status
"""
from __future__ import annotations

import argparse
import datetime as dt
import sys
from collections import Counter
from pathlib import Path

import yaml
from openpyxl import Workbook, load_workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.worksheet.datavalidation import DataValidation

ROOT = Path(__file__).resolve().parents[1]
REWORDINGS = ROOT / "evals" / "rewordings.yaml"
REVIEW_XLSX = ROOT / "data" / "review" / "rewordings_review.xlsx"
STATUSES = {"pending", "approved", "rejected"}

HEADER = """# Alternate phrasings of golden-set questions, in the styles real buyers use.
#
# Each rewording inherits ALL expectations of its golden question (status,
# citations, facts, routing). That is only valid if the rewording asks the same
# thing, so every rewording starts as `pending` and is used in scored runs only
# after a human approves it:
#
#   python -m tools.rewordings export   -> data/review/rewordings_review.xlsx
#   (reviewer fills the Decision column: approve / reject / edit)
#   python -m tools.rewordings import   -> updates the status fields below
#
# status: pending | approved | rejected
# source: author of the draft (claude-authored = written by Claude, llm = generated by tools.rewordings propose)
"""


def load(path: Path = REWORDINGS) -> dict[str, list[dict]]:
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return data.get("rewordings") or {}


def save(rewordings: dict[str, list[dict]], path: Path = REWORDINGS) -> None:
    """Write in the same compact, diff-friendly format as the hand-written file."""
    def q(s: str) -> str:
        return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'

    lines = [HEADER, "version: 1", "rewordings:"]
    for gid, items in rewordings.items():
        lines.append(f"  {gid}:")
        for r in items:
            extra = "".join(f", {k}: {q(r[k])}" for k in ("reviewer", "reviewed_on", "note") if r.get(k))
            lines.append(f"    - {{id: {r['id']}, status: {r['status']}, source: {r.get('source', 'unknown')}"
                         f"{extra}, text: {q(r['text'])}}}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def validate(rewordings: dict[str, list[dict]], golden_ids: set[str]) -> list[str]:
    errors, seen = [], set()
    for gid, items in rewordings.items():
        if gid not in golden_ids:
            errors.append(f"{gid}: not a golden-set id")
        for r in items:
            rid = r.get("id", "?")
            if rid in seen:
                errors.append(f"{rid}: duplicate id")
            seen.add(rid)
            if not rid.startswith(gid + "-R"):
                errors.append(f"{rid}: id must start with {gid}-R")
            if r.get("status") not in STATUSES:
                errors.append(f"{rid}: bad status {r.get('status')!r}")
            if not str(r.get("text", "")).strip():
                errors.append(f"{rid}: empty text")
    return errors


def _golden() -> dict[str, dict]:
    from evals.validate_golden_set import load_golden
    return {q["id"]: q for q in load_golden()["questions"]}


def _expected_summary(q: dict) -> str:
    s = q["expected_status"]
    if q["category"] == "covered":
        return f"answered; must state: {', '.join(q['required_facts'])}"
    if q["category"] == "conflict":
        vals = " vs ".join(str(x["value"]) for x in q["conflict"]["sources"])
        return f"conflict on {q['conflict']['topic']} ({vals})"
    if q["category"] == "sensitive":
        return f"escalated to {q['route_to']}"
    if q["category"] == "ambiguous":
        return "needs clarification: " + "; ".join(q["clarification_options"])
    return f"{s} (topic not in approved docs)"


# --- export / import --------------------------------------------------------

def export_review(out: Path = REVIEW_XLSX, only_pending: bool = True, store: Path = REWORDINGS) -> int:
    golden, rew = _golden(), load(store)
    out.parent.mkdir(parents=True, exist_ok=True)
    wb = Workbook()
    ws = wb.active
    ws.title = "Review"
    headers = ["Rewording ID", "Category", "Original question", "Rewording", "Expected behavior (inherited)",
               "Current status", "Decision", "Edited text (if edit)", "Reviewer", "Notes"]
    ws.append(headers)
    for c in ws[1]:
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor="1F3A5F")
        c.alignment = Alignment(wrap_text=True, vertical="center")
    n = 0
    for gid, items in rew.items():
        q = golden[gid]
        for r in items:
            if only_pending and r["status"] != "pending":
                continue
            ws.append([r["id"], q["category"], q["question"], r["text"], _expected_summary(q),
                       r["status"], "", "", "", ""])
            n += 1
    dv = DataValidation(type="list", formula1='"approve,reject,edit"', allow_blank=True)
    ws.add_data_validation(dv)
    dv.add(f"G2:G{max(ws.max_row, 2)}")
    for col, w in zip("ABCDEFGHIJ", [14, 12, 45, 45, 40, 11, 11, 40, 14, 30]):
        ws.column_dimensions[col].width = w
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment = Alignment(wrap_text=True, vertical="top")
    ws.freeze_panes = "A2"
    guide = wb.create_sheet("How to review")
    for line in [
        "Approve a rewording only if it asks exactly the same thing as the original question,",
        "so the inherited expected behavior (column E) is still correct.",
        "",
        "Watch for rewordings that: narrow or widen the question; add a commitment word such as",
        "'guarantee' or 'contractually' (which can turn a factual question into a sensitive one);",
        "remove the word that made a question ambiguous; or introduce a term the documents cover.",
        "",
        "Decision: approve | reject | edit (put the corrected wording in column H; it is approved as edited).",
        "Then run:  python -m tools.rewordings import",
    ]:
        guide.append([line])
    guide.column_dimensions["A"].width = 100
    wb.save(out)
    return n


def import_review(path: Path = REVIEW_XLSX, store: Path = REWORDINGS) -> Counter:
    rew = load(store)
    by_id = {r["id"]: r for items in rew.values() for r in items}
    ws = load_workbook(path)["Review"]
    changes: Counter = Counter()
    today = dt.date.today().isoformat()
    for row in ws.iter_rows(min_row=2, values_only=True):
        rid, decision, edited, reviewer, note = row[0], row[6], row[7], row[8], row[9]
        if not rid or not decision:
            continue
        decision = str(decision).strip().lower()
        r = by_id.get(rid)
        if r is None:
            raise SystemExit(f"{rid}: not found in {store.name}")
        if decision == "approve":
            r["status"] = "approved"
        elif decision == "reject":
            r["status"] = "rejected"
        elif decision == "edit":
            if not edited or not str(edited).strip():
                raise SystemExit(f"{rid}: decision 'edit' needs text in 'Edited text'")
            r["text"], r["status"] = str(edited).strip(), "approved"
        else:
            raise SystemExit(f"{rid}: unknown decision {decision!r} (use approve / reject / edit)")
        r["reviewed_on"] = today
        if reviewer:
            r["reviewer"] = str(reviewer)
        if note:
            r["note"] = str(note)
        changes[decision] += 1
    save(rew, store)
    return changes


# --- propose new drafts with Claude ------------------------------------------

PROPOSE_PROMPT = """You write alternate phrasings of questions from vendor security questionnaires and RFPs.
Rules:
- Ask EXACTLY the same thing as the original: same scope, same number of sub-questions.
- Do not add commitment language (guarantee, warrant, contractually commit) unless the original has it.
- If the original is deliberately vague, keep it equally vague.
- Vary style the way real buyers do: terse spreadsheet shorthand, formal "The vendor shall describe...",
  "Confirm that...", plain-English questions.
Return JSON: {"rewordings": ["...", "..."]}"""


def propose(per_question: int, ids: list[str] | None = None) -> int:
    from agents.llm import get_llm  # imported lazily: needs ANTHROPIC_API_KEY
    llm, golden, rew = get_llm(), _golden(), load()
    added = 0
    for gid, q in golden.items():
        if ids and gid not in ids:
            continue
        existing = rew.setdefault(gid, [])
        out = llm.json(system=PROPOSE_PROMPT,
                       user=f"Original question: {q['question']}\nWrite {per_question} alternate phrasings.",
                       purpose="propose_rewordings")
        start = max([int(r["id"].rsplit("-R", 1)[1]) for r in existing] or [0]) + 1
        for i, text in enumerate(out.get("rewordings", [])[:per_question]):
            existing.append({"id": f"{gid}-R{start + i}", "status": "pending", "source": "llm", "text": text})
            added += 1
    save(rew)
    return added


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    e = sub.add_parser("export")
    e.add_argument("--all", action="store_true", help="include already-reviewed rewordings")
    e.add_argument("--out", type=Path, default=REVIEW_XLSX)
    i = sub.add_parser("import")
    i.add_argument("file", nargs="?", type=Path, default=REVIEW_XLSX)
    p = sub.add_parser("propose")
    p.add_argument("--per-question", type=int, default=2)
    p.add_argument("--ids", default="")
    sub.add_parser("status")
    a = ap.parse_args(argv)

    if a.cmd == "export":
        n = export_review(a.out, only_pending=not a.all)
        print(f"Wrote {n} rewordings for review to {a.out}")
    elif a.cmd == "import":
        print("Applied:", dict(import_review(a.file)) or "no decisions found")
    elif a.cmd == "propose":
        print(f"Added {propose(a.per_question, [x for x in a.ids.split(',') if x])} pending rewordings")
    errs = validate(load(), set(_golden()))
    counts = Counter(r["status"] for items in load().values() for r in items)
    print("Rewordings:", dict(counts))
    for e_ in errs:
        print("  -", e_)
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main())
